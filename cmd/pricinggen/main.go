package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strconv"

	"github.com/Guilherme-Ciano/evalvet/internal/pricing"
)

func floatPtr(p *float64) string {
	if p == nil {
		return "nil"
	}
	return "fp(" + strconv.FormatFloat(*p, 'g', -1, 64) + ")"
}

func rates(r pricing.Rates) string {
	return fmt.Sprintf("Rates{Input: %s, Output: %s, CachedInput: %s, CacheWrite: %s}",
		strconv.FormatFloat(r.Input, 'g', -1, 64), strconv.FormatFloat(r.Output, 'g', -1, 64),
		floatPtr(r.CachedInput), floatPtr(r.CacheWrite))
}

func generate(t pricing.Table) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/pricinggen. DO NOT EDIT.\n\n")
	b.WriteString("package pricing\n\n")
	b.WriteString("func fp(v float64) *float64 { return &v }\n\n")
	b.WriteString("func Builtin() Table {\n\treturn Table{\n")
	fmt.Fprintf(&b, "\t\tVersion: %q,\n\t\tCurrency: %q,\n\t\tModels: []Entry{\n", t.Version, t.Currency)
	for _, e := range t.Models {
		fmt.Fprintf(&b, "\t\t\t{Provider: %q, Model: %q, EffectiveFrom: %q, PerMTok: %s", e.Provider, e.Model, e.EffectiveFrom, rates(e.PerMTok))
		if len(e.Tiers) > 0 {
			b.WriteString(", Tiers: []Tier{")
			for _, tier := range e.Tiers {
				fmt.Fprintf(&b, "{AboveInputTokens: %d, PerMTok: %s},", tier.AboveInputTokens, rates(tier.PerMTok))
			}
			b.WriteString("}")
		}
		b.WriteString("},\n")
	}
	b.WriteString("\t\t},\n\t}\n}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w", err)
	}
	return out, nil
}

func main() {
	in := flag.String("in", "pricing/pricing.yaml", "pricing YAML")
	out := flag.String("out", "internal/pricing/table_gen.go", "generated Go file")
	flag.Parse()
	t, err := pricing.LoadFile(*in)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(2)
	}
	src, err := generate(t)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, src, 0o600); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
