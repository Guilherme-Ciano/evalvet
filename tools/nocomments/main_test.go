package main

import (
	"bytes"
	"go/token"
	"os"
	"path/filepath"
	"testing"
)

func TestCheckSource(t *testing.T) {
	t.Parallel()
	cases := []struct {
		name string
		src  string
		want int
	}{
		{"line comment", "package p\n// x\nfunc f() {}\n", 1},
		{"block comment", "package p\n/* x */\nfunc f() {}\n", 1},
		{"directive", "//go:build linux\n\npackage p\n", 0},
		{"generated header", "// Code generated by x. DO NOT EDIT.\n\npackage p\n", 0},
		{"nolint", "package p\nfunc f() {} //nolint:all\n", 1},
		{"string with slashes", "package p\nconst s = \"// not a comment\"\n", 0},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got, err := checkSource(token.NewFileSet(), "x.go", tc.src)
			if err != nil {
				t.Fatal(err)
			}
			if len(got) != tc.want {
				t.Fatalf("got %d violations %v, want %d", len(got), got, tc.want)
			}
		})
	}
}

func TestRun(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	clean := filepath.Join(dir, "clean")
	dirty := filepath.Join(dir, "dirty")
	for _, d := range []string{clean, dirty, filepath.Join(dirty, "testdata")} {
		if err := os.MkdirAll(d, 0o750); err != nil {
			t.Fatal(err)
		}
	}
	write := func(p, s string) {
		if err := os.WriteFile(p, []byte(s), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	write(filepath.Join(clean, "a.go"), "package a\n")
	write(filepath.Join(dirty, "b.go"), "package b\n// hi\n")
	write(filepath.Join(dirty, "testdata", "c.go"), "package c\n// ignored\n")
	var out, errOut bytes.Buffer
	if code := run([]string{clean}, &out, &errOut); code != 0 {
		t.Fatalf("clean: code %d, stderr %s", code, errOut.String())
	}
	errOut.Reset()
	if code := run([]string{dirty}, &out, &errOut); code != 1 {
		t.Fatalf("dirty: code %d", code)
	}
	if code := run([]string{filepath.Join(dir, "missing")}, &out, &errOut); code != 2 {
		t.Fatalf("missing: code %d", code)
	}
}
